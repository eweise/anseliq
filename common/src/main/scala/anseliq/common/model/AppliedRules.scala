package anseliq.common.model

import upickle.default.ReadWriter

/**
 * One leaf match rule (a StringAttributeMatchRule or DateAttributeMatchRule) of a reconciliation
 * spec's rule, paired with the key value every movement in the group shared under it. `value` is
 * post-modifier (e.g. the DateAdd-shifted date), i.e. exactly what the two sides compared equal on.
 * The rule itself is stored rather than referenced, so this stays an accurate snapshot even if the
 * spec's rule_json is later edited.
 */
case class RuleMatch(rule: Rule, value: String) derives ReadWriter:
  /** The rule's condition alone (e.g. `txnDate + 2 Day = settleDate`), without the matched value. */
  def condition: String =
    rule match
      case s: StringAttributeMatchRule => s"${RuleMatch.describe(s.inKey)} = ${RuleMatch.describe(s.outKey)}"
      case d: DateAttributeMatchRule   => s"${RuleMatch.describe(d.inKey)} = ${RuleMatch.describe(d.outKey)}"
      case other                       => other.sql

  def summary: String = s"$condition: $value"

object RuleMatch:
  private def describe(attr: StringAttribute): String =
    if attr.isConstant then s"'${attr.key}'" else attr.key

  private def describe(attr: DateAttribute): String =
    val base = if attr.isConstant then s"'${attr.key}'" else attr.key
    attr.modifier match
      case None                       => base
      case Some(DateAdd(interval, v)) => s"$base + $v $interval"

/** Why a reconciliation's movements were grouped together — persisted as jsonb in applied_rules. */
enum AppliedRules derives ReadWriter:
  /** Formed by the reconciler: one RuleMatch per leaf rule, in rule order. */
  case Matched(matches: List[RuleMatch])

  /** Formed by a user via ManualReconciler. */
  case Manual

  /**
   * Formed by a user accepting a secondary matcher's suggestion (see MatchSuggestionService): which
   * model proposed it, how sure it was and why. The reviewer is recorded on the suggestion.
   */
  case Suggested(suggestionId: String, model: String, promptVersion: String, confidence: BigDecimal, reason: String)

  /** System-generated by Ledger.reverseMovement (see ReconciliationStatus.Reversed). */
  case Reversal

  def summary: String =
    this match
      case Matched(matches) => matches.map(_.summary).mkString("; ")
      case Manual           => "manual"
      case s: Suggested     => s"suggested by ${s.model} (${(s.confidence * 100).setScale(0, BigDecimal.RoundingMode.HALF_UP)}%): ${s.reason}"
      case Reversal         => "system: reversal"
